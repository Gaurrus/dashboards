#!/usr/bin/env python3
"""Generate include/version.h and the Arduino copy from the VERSION file.

Standalone:  python3 scripts/gen_version.py
PlatformIO:  extra_scripts = pre:../scripts/gen_version.py
"""
from __future__ import annotations

import re
from pathlib import Path

try:  # PlatformIO/SCons pre-script: __file__ is not defined by exec()
    Import("env")  # type: ignore[name-defined]
    ROOT = Path(env.subst("$PROJECT_DIR")).resolve().parent  # type: ignore[name-defined]
    _PLATFORMIO = True
except NameError:
    ROOT = Path(__file__).resolve().parent.parent
    _PLATFORMIO = False

VERSION_FILE = ROOT / "VERSION"
HEADER = ROOT / "include" / "version.h"
ARDUINO_HEADER = ROOT / "arduino" / "t3-dash" / "version.h"

SEMVER = re.compile(r"^\d+\.\d+\.\d+$")


def generate() -> None:
    version = VERSION_FILE.read_text(encoding="utf-8").strip()
    if not SEMVER.match(version):
        raise SystemExit(f"VERSION must be MAJOR.MINOR.PATCH, got: {version!r}")

    content = (
        "// Generated by scripts/gen_version.py from VERSION. Do not edit.\n"
        "#pragma once\n\n"
        f'#define T3DASH_VERSION "{version}"\n'
    )
    HEADER.parent.mkdir(parents=True, exist_ok=True)
    HEADER.write_text(content, encoding="utf-8")
    ARDUINO_HEADER.parent.mkdir(parents=True, exist_ok=True)
    ARDUINO_HEADER.write_text(content, encoding="utf-8")
    print(f"version.h: {version}")


if _PLATFORMIO:
    generate()
elif __name__ == "__main__":
    generate()
